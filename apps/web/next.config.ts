import type { NextConfig } from 'next';

const dev = process.env.NODE_ENV === 'development';
const engine = new URL(process.env.NEXT_PUBLIC_ENGINE_URL ?? 'http://localhost:8787').origin;

// No nonces: Next's inline scripts need 'unsafe-inline', and pages stay static. The parts that
// matter for the key paste: nothing can frame the app, and the page can only talk to the engine.
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${dev ? " 'unsafe-eval'" : ''}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  `connect-src 'self' ${engine}${dev ? ' ws:' : ''}`,
  "worker-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');

const config: NextConfig = {
  distDir: process.env.AIRBAG_E2E ? '.next-e2e' : '.next',
  reactStrictMode: true,
  poweredByHeader: false,
  async headers() {
    return [
      {
        source: '/(.*)',
        headers: [
          { key: 'Content-Security-Policy', value: csp },
          { key: 'X-Content-Type-Options', value: 'nosniff' },
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
          { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=()' },
          {
            key: 'Strict-Transport-Security',
            value: 'max-age=63072000; includeSubDomains',
          },
        ],
      },
    ];
  },
};

export default config;
